import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const p = await b.newPage({ viewport: { width: 1280, height: 820 } });
const bad = [];
p.on('response', r => { if (r.status() >= 400) bad.push(`${r.status()} ${r.url().split('/').pop()}`); });
await p.goto('http://localhost:5183/?turn=60000', { waitUntil: 'networkidle' });
await p.waitForTimeout(1500);
await p.getByRole('button', { name: /狐.*狡狐/ }).first().click();
await p.waitForTimeout(400);
await p.getByRole('button', { name: /入座/ }).first().click();
await p.waitForSelector('canvas');
await p.waitForFunction(() => !!window.__STORE__);
await p.waitForTimeout(14000);
const sfx = await p.evaluate(() => {
  const s = window.__SND__;
  return typeof s === 'object' ? Object.keys(s).slice(0, 6) : 'no probe';
});
console.log('404:', bad.length ? bad : '无');
console.log('音效探针:', JSON.stringify(sfx).slice(0, 100));
console.log('语音记录:', await p.evaluate(() => (window.__VOICE__ ?? []).length));
await b.close();
