import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
const errs = [];
p.on('pageerror', e => errs.push('PAGEERROR: ' + e.message.slice(0, 200)));
p.on('console', m => { if (m.type() === 'error') errs.push('CONSOLE: ' + m.text().slice(0, 200)); });
await p.goto('http://localhost:5183/', { waitUntil: 'networkidle' });
await p.waitForTimeout(2000);
console.log('--- 点法师 ---');
await p.getByRole('button', { name: /法.*法师/ }).first().click();
await p.waitForTimeout(3000);
await p.screenshot({ path: '/tmp/err-mage.png' });
console.log('错误:', errs.length ? errs.slice(0, 3) : '无');
errs.length = 0;
console.log('--- 点浪人 ---');
await p.getByRole('button', { name: /浪.*浪人/ }).first().click();
await p.waitForTimeout(3000);
await p.screenshot({ path: '/tmp/err-rogue.png' });
console.log('错误:', errs.length ? errs.slice(0, 3) : '无');
await b.close();
