import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
const reqs = [];
p.on('response', r => { if (/\.glb|draco/.test(r.url())) reqs.push(`${r.status()} ${r.url().split('/').pop()}`); });
const errs = [];
p.on('pageerror', e => errs.push(e.message));
p.on('console', m => { if (m.type() === 'error') errs.push(m.text().slice(0, 100)); });
await p.goto('http://localhost:5183/', { waitUntil: 'networkidle' });
await p.waitForTimeout(2000);
await p.getByText('老法师·奥登').click();
await p.waitForTimeout(5000);
console.log('GLB/draco 请求:', reqs.slice(-8));
console.log('错误:', errs.slice(0, 3));
await b.close();
